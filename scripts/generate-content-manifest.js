import {
  STATES, SEED_CITIES, SERVICES, COST_PAGE_CITIES,
  cityToSlug, buildSlug,
  isCityQualifiedForService, isStateQualifiedForService,
} from '../lib/cities.js';
import { getAllPlaces, getPlacesByState } from '../lib/nationwidePlaces.js';
import { getZctasByState, SERVICE_SLUGS } from '../lib/hyperlocalPlaces-server.js';
import { isZctaQualifiedForService } from '../lib/hyperlocalPlaces.js';
import fs from 'fs';
import path from 'path';
import { updateManifestEntries, hashContent } from '../lib/contentHash.js';

const MANIFEST_FILE = '.content-manifest.json';
const DATES_FILE = 'lib/.content-dates.js';

function loadManifest() {
  try {
    const raw = fs.readFileSync(path.join(process.cwd(), MANIFEST_FILE), 'utf-8');
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

function saveManifest(manifest) {
  fs.writeFileSync(path.join(process.cwd(), MANIFEST_FILE), JSON.stringify(manifest, null, 2) + '\n', 'utf-8');
}

function saveDatesFile(manifest) {
  const dates = {};
  for (const [key, entry] of Object.entries(manifest)) {
    dates[key] = entry.date;
  }
  const content = '// AUTO-GENERATED by scripts/generate-content-manifest.js — do not edit\nexport const dates = ' + JSON.stringify(dates, null, 2) + ';\n';
  fs.writeFileSync(path.join(process.cwd(), DATES_FILE), content, 'utf-8');
}

const ZCTA_SITEMAP_SERVICES = [
  'emergency',
  'leak-repair',
  'drain-cleaning',
  'water-heater-repair',
  'pipe-burst-repair',
];

const GUIDES = [
  'how-to-prevent-frozen-pipes',
  'signs-you-need-a-plumber',
  'how-to-shut-off-water-in-emergency',
  'hard-water-effects-on-plumbing',
  'water-heater-maintenance-guide',
];

function collectAllPageEntries() {
  const entries = [];

  // Static pages
  entries.push({ pageKey: 'static:home', hash: hashContent('home') });
  entries.push({ pageKey: 'static:plumber-usa', hash: hashContent('plumber-usa') });
  entries.push({ pageKey: 'static:plumbing-cost-guide', hash: hashContent('plumbing-cost-guide') });
  entries.push({ pageKey: 'static:about', hash: hashContent('about') });
  entries.push({ pageKey: 'static:contact', hash: hashContent('contact') });
  entries.push({ pageKey: 'static:faq', hash: hashContent('faq') });
  entries.push({ pageKey: 'static:disclaimer', hash: hashContent('disclaimer') });
  entries.push({ pageKey: 'static:privacy-policy', hash: hashContent('privacy-policy') });
  entries.push({ pageKey: 'static:terms-of-service', hash: hashContent('terms-of-service') });
  entries.push({ pageKey: 'static:guides', hash: hashContent('guides') });
  entries.push({ pageKey: 'static:research-us-water-hardness', hash: hashContent('research') });
  entries.push({ pageKey: 'static:whats-wrong', hash: hashContent('whats-wrong') });
  entries.push({ pageKey: 'static:why-trust', hash: hashContent('why-trust') });
  entries.push({ pageKey: 'static:how-works', hash: hashContent('how-works') });
  entries.push({ pageKey: 'static:authors', hash: hashContent('authors') });
  entries.push({ pageKey: 'static:editorial-policy', hash: hashContent('editorial-policy') });
  entries.push({ pageKey: 'static:sources', hash: hashContent('sources') });
  entries.push({ pageKey: 'static:press', hash: hashContent('press') });
  entries.push({ pageKey: 'static:media-kit', hash: hashContent('media-kit') });
  ['editorial-team', 'plumbing-standards-reviewer', 'home-services-researcher'].forEach(slug => {
    entries.push({ pageKey: `author:${slug}`, hash: hashContent(`author-${slug}`) });
  });

  // Guide pages
  GUIDES.forEach(slug => {
    entries.push({ pageKey: `guide:${slug}`, hash: hashContent(`guide-${slug}`) });
  });

  // State hub pages
  STATES.forEach(s => {
    entries.push({ pageKey: `state:${s.slug}`, hash: hashContent(`state-${s.slug}`) });
  });

  // State × Service pages
  STATES.forEach(s => {
    SERVICES.forEach(svc => {
      if (isStateQualifiedForService(s.code, svc.slug)) {
        entries.push({
          pageKey: `state-service:${s.slug}:${svc.slug}`,
          hash: hashContent(`plumber-${s.slug}-${svc.slug}`),
        });
      }
    });
  });

  // Cost page cities
  COST_PAGE_CITIES.forEach(cityName => {
    entries.push({ pageKey: `cost:${cityToSlug(cityName)}`, hash: hashContent(`cost-${cityName}`) });
  });

  // SEED_CITIES × Services (city-service pages)
  SEED_CITIES.forEach(city => {
    const cSlug = cityToSlug(city.name);
    SERVICES.forEach(svc => {
      if (isCityQualifiedForService(city.name, svc.slug, city.stateCode)) {
        const fullSlug = buildSlug(cSlug, svc.slug);
        entries.push({
          pageKey: `city-service:${fullSlug}`,
          hash: hashContent(`${city.name}:${city.stateCode}:${svc.slug}`),
        });
      }
    });
  });

  // Nationwide places × Services (same URL pattern, different data source)
  const seedCityNames = new Set(SEED_CITIES.map(c => c.name));
  getAllPlaces().forEach(place => {
    if (seedCityNames.has(place.name)) return;
    SERVICES.forEach(svc => {
      if (isCityQualifiedForService(place.name, svc.slug, place.stateCode)) {
        const fullSlug = buildSlug(place.slug, svc.slug);
        entries.push({
          pageKey: `city-service:${fullSlug}`,
          hash: hashContent(`${place.name}:${place.stateCode}:${svc.slug}`),
        });
      }
    });
  });

  // ZCTA area directory pages (city-level)
  const citySlugsWithZctas = new Set();
  STATES.forEach(s => {
    const stateZctas = getZctasByState(s.code);
    stateZctas.forEach(z => citySlugsWithZctas.add(z.parentCitySlug));
  });
  citySlugsWithZctas.forEach(citySlug => {
    entries.push({ pageKey: `zcta-city:${citySlug}`, hash: hashContent(`areas-${citySlug}`) });
  });

  // ZCTA × Service pages
  STATES.forEach(s => {
    const stateZctas = getZctasByState(s.code);
    stateZctas.forEach(zcta => {
      ZCTA_SITEMAP_SERVICES.forEach(svc => {
        if (isZctaQualifiedForService(zcta, svc)) {
          entries.push({
            pageKey: `zcta-service:${zcta.parentCitySlug}:${zcta.zip}:${svc}`,
            hash: hashContent(`${zcta.zip}:${zcta.parentCitySlug}:${svc}`),
          });
        }
      });
    });
  });

  return entries;
}

function main() {
  console.log('[content-manifest] Collecting page entries...');
  const entries = collectAllPageEntries();
  console.log(`[content-manifest] Found ${entries.length} pages`);

  const existing = loadManifest();
  const updated = updateManifestEntries(existing, entries);

  const newCount = entries.filter(e => {
    const old = existing[e.pageKey];
    return !old || old.hash !== e.hash;
  }).length;

  saveManifest(updated);
  saveDatesFile(updated);
  console.log(`[content-manifest] ${newCount} pages updated, ${entries.length - newCount} unchanged`);
  console.log('[content-manifest] Manifest saved to .content-manifest.json');
  console.log(`[content-manifest] Dates file saved to ${DATES_FILE}`);
}

main();
